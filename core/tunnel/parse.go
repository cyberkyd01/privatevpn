// Pure parsers for OS command output and state files. They live in an
// untagged file so they are unit tested on every OS.

// ---- Linux ----

const capNetAdmin = 12

// hasCapNetAdmin parses /proc/self/status and reports whether CapEff
// contains CAP_NET_ADMIN.
func hasCapNetAdmin(status []byte) bool {
	sc := bufio.NewScanner(bytes.NewReader(status))
	for sc.Scan() {
		k, v, ok := strings.Cut(sc.Text(), ":")
		if !ok || k != "CapEff" {
			continue
		}
		caps, err := strconv.ParseUint(strings.TrimSpace(v), 16, 64)
		return err == nil && caps&(1<<capNetAdmin) != 0
	}
	return false
}

// resolvConfUsesResolved reports whether /etc/resolv.conf (symlink target
// and content) hands queries to systemd-resolved's stub, in which case
// per-link resolvectl settings are effective.
func resolvConfUsesResolved(linkTarget string, content []byte) bool {
	if strings.Contains(linkTarget, "/run/systemd/resolve/") || strings.Contains(linkTarget, "/systemd/resolv.conf") {
		return true
	}
	sc := bufio.NewScanner(bytes.NewReader(content))
	for sc.Scan() {
		f := strings.Fields(sc.Text())
		if len(f) >= 2 && f[0] == "nameserver" && (f[1] == "127.0.0.53" || f[1] == "127.0.0.54") {
			return true
		}
	}
	return false
}

// resolvConfContent renders our /etc/resolv.conf.
func resolvConfContent(dns []netip.Addr) []byte {
	var b strings.Builder
	b.WriteString("# Generated by Private VPN Pro while the client tunnel is up; the original is restored on disconnect.\n")
	for _, d := range dns {
		b.WriteString("nameserver " + d.String() + "\n")
	}
	return []byte(b.String())
}

// ---- macOS ----

// parseNetworkServices parses `networksetup -listallnetworkservices`,
// returning enabled services (disabled ones start with '*').
func parseNetworkServices(out []byte) []string {
	var svcs []string
	sc := bufio.NewScanner(bytes.NewReader(out))
	first := true
	for sc.Scan() {
		line := strings.TrimRight(sc.Text(), "\r")
		if first {
			first = false
			if strings.HasPrefix(line, "An asterisk") {
				continue
			}
		}
		if line == "" || strings.HasPrefix(line, "*") || !validServiceName(line) {
			continue
		}
		svcs = append(svcs, line)
	}
	return svcs
}

// validServiceName bounds what we pass back to networksetup as an argument.
func validServiceName(s string) bool {
	if s == "" || len(s) > 256 || !utf8.ValidString(s) || strings.HasPrefix(s, "-") {
		return false
	}
	for _, r := range s {
		if r < 0x20 || r == 0x7f {
			return false
		}
	}
	return true
}

// parseDNSServers parses `networksetup -getdnsservers <svc>`. ok=false means
// the output was not understood and the service must be left alone.
func parseDNSServers(out []byte) (servers []string, ok bool) {
	text := strings.TrimSpace(string(out))
	if strings.HasPrefix(text, "There aren't any DNS Servers set") {
		return nil, true
	}
	if text == "" {
		return nil, false
	}
	for _, line := range strings.Split(text, "\n") {
		a, err := netip.ParseAddr(strings.TrimSpace(line))
		if err != nil {
			return nil, false
		}
		servers = append(servers, a.String())
	}
	return servers, true
}

// parseRouteGetDefault parses `route -n get default` (fallback when the RIB
// cannot be read): returns the gateway (may be invalid for interface
// routes) and the interface name.
func parseRouteGetDefault(out []byte) (gw netip.Addr, ifname string, ok bool) {
	sc := bufio.NewScanner(bytes.NewReader(out))
	for sc.Scan() {
		k, v, found := strings.Cut(strings.TrimSpace(sc.Text()), ":")
		if !found {
			continue
		}
		v = strings.TrimSpace(v)
		switch strings.TrimSpace(k) {
		case "gateway":
			if a, err := netip.ParseAddr(v); err == nil && a.Is4() {
				gw = a
			}
		case "interface":
			ifname = v
		}
	}
	return gw, ifname, ifname != ""
}

// dnsBackup is the crash-safe record of macOS DNS settings (§9.3).
type dnsBackup struct {
	Version  int              `json:"version"`
	Services []dnsBackupEntry `json:"services"`
}

type dnsBackupEntry struct {
	Name    string   `json:"name"`
	Servers []string `json:"servers"` // empty = "Empty" (DHCP-provided)
}

func encodeDNSBackup(b dnsBackup) ([]byte, error) {
	b.Version = 1
	return json.Marshal(b)
}

// decodeDNSBackup parses and strictly validates a backup file.
func decodeDNSBackup(data []byte) (dnsBackup, error) {
	var b dnsBackup
	if len(data) > 64<<10 {
		return b, errors.New("dns backup: too large")
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&b); err != nil || b.Version != 1 || len(b.Services) > 64 {
		return dnsBackup{}, errors.New("dns backup: malformed")
	}
	for _, e := range b.Services {
		if !validServiceName(e.Name) || len(e.Servers) > 16 {
			return dnsBackup{}, errors.New("dns backup: malformed")
		}
		for _, s := range e.Servers {
			if _, err := netip.ParseAddr(s); err != nil {
				return dnsBackup{}, errors.New("dns backup: malformed")
			}
		}
	}
	return b, nil
}

// setDNSArgs returns the networksetup arguments that apply servers to svc
// ("Empty" restores the DHCP-provided resolvers).
func setDNSArgs(svc string, servers []string) []string {
	args := []string{"-setdnsservers", svc}
	if len(servers) == 0 {
		return append(args, "Empty")
	}
	return append(args, servers...)
}
