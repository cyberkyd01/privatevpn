func ipnet(s string) net.Addr {
	p := netip.MustParsePrefix(s)
	return &net.IPNet{IP: net.IP(p.Addr().AsSlice()), Mask: net.CIDRMask(p.Bits(), p.Addr().BitLen())}
}

