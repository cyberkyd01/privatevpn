// scriptedSnap returns successive canned snapshots (an empty string means
// an error), repeating the last one.
type scriptedSnap struct {
	mu    sync.Mutex
	seq   []string
	i     int
	calls int
}

func (s *scriptedSnap) snap() (string, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.calls++
	v := s.seq[min(s.i, len(s.seq)-1)]
	s.i++
	if v == "" {
		return "", errors.New("interfaces unavailable")
	}
	return v, nil
}

func (s *scriptedSnap) callCount() int {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.calls
}

func TestWatcherDiff(t *testing.T) {
	// initial "a"; then a, b (change), b, "" (error: ignored), b, c (change), c...
	s := &scriptedSnap{seq: []string{"a", "a", "b", "b", "", "b", "c", "c"}}
	var changes atomic.Int32
	w := newWatcher(5*time.Millisecond, func() { changes.Add(1) }, s.snap)
	deadline := time.Now().Add(5 * time.Second)
	for s.callCount() < 12 && time.Now().Before(deadline) {
		time.Sleep(2 * time.Millisecond)
	}
	w.Stop()
	if n := changes.Load(); n != 2 {
		t.Errorf("onChange called %d times, want 2", n)
	}
	n := s.callCount()
	time.Sleep(30 * time.Millisecond)
	if s.callCount() != n {
		t.Error("polling continued after Stop")
	}
	w.Stop() // idempotent
}

func TestWatcherInitialErrorThenSuccess(t *testing.T) {
	s := &scriptedSnap{seq: []string{"", "", "a", "a"}}
	var changes atomic.Int32
	w := newWatcher(5*time.Millisecond, func() { changes.Add(1) }, s.snap)
	deadline := time.Now().Add(5 * time.Second)
	for s.callCount() < 8 && time.Now().Before(deadline) {
		time.Sleep(2 * time.Millisecond)
	}
	w.Stop()
	if n := changes.Load(); n != 1 {
		t.Errorf("onChange called %d times, want 1 (interfaces appeared)", n)
	}
}

func TestWatcherAtMostOncePerInterval(t *testing.T) {
	var i atomic.Int64
	snap := func() (string, error) { return strconv.Itoa(int(i.Add(1) % 100)), nil } // changes on every poll
	var mu sync.Mutex
	var at []time.Time
	interval := 20 * time.Millisecond
	w := newWatcher(interval, func() { mu.Lock(); at = append(at, time.Now()); mu.Unlock() }, snap)
	time.Sleep(200 * time.Millisecond)
	w.Stop()
	mu.Lock()
	defer mu.Unlock()
	if len(at) < 2 {
		t.Fatalf("only %d changes", len(at))
	}
	for k := 1; k < len(at); k++ {
		if gap := at[k].Sub(at[k-1]); gap < interval/2 {
			t.Errorf("onChange calls %v apart, interval %v", gap, interval)
		}
	}
}

func TestSnapshotOfCanonical(t *testing.T) {
	ifs := []net.Interface{
		{Index: 2, Name: "en0", Flags: net.FlagUp | net.FlagBroadcast | net.FlagRunning},
		{Index: 1, Name: "lo0", Flags: net.FlagUp | net.FlagLoopback},
	}
	addrs := map[string][]net.Addr{
		"en0": {ipnet("192.168.1.10/24"), ipnet("fe80::1/64")},
		"lo0": {ipnet("127.0.0.1/8")},
	}
	of := func(ifi net.Interface) ([]net.Addr, error) { return addrs[ifi.Name], nil }
	a := snapshotOf(ifs, of)
	// Reordered interfaces and addresses, and an irrelevant flag change: same snapshot.
	ifs[0], ifs[1] = ifs[1], ifs[0]
	ifs[1].Flags &^= net.FlagBroadcast
	addrs["en0"] = []net.Addr{ipnet("fe80::1/64"), ipnet("192.168.1.10/24")}
	if b := snapshotOf(ifs, of); a != b {
		t.Errorf("snapshot not canonical:\n%s\n%s", a, b)
	}
	addrs["en0"] = []net.Addr{ipnet("192.168.1.20/24")}
	if c := snapshotOf(ifs, of); c == a {
		t.Error("address change not detected")
	}
	addrs["en0"] = []net.Addr{ipnet("fe80::1/64"), ipnet("192.168.1.10/24")}
	ifs[1].Flags &^= net.FlagUp
	if d := snapshotOf(ifs, of); d == a {
		t.Error("interface down not detected")
	}
}

