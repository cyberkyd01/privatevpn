func TestLiveValues(t *testing.T) {
	if v := OSVersion(); v == "" || utf8.RuneCountInString(v) > maxOSVersion {
		t.Errorf("OSVersion() = %q", v)
	}
	if OSVersion() != OSVersion() {
		t.Error("OSVersion not stable")
	}
	if u := Uptime(); u <= 0 || u > 10*365*24*time.Hour {
		t.Errorf("Uptime() = %v", u)
	}
	name, off, abbrev := TimeZone()
	wantAbbrev, wantOff := time.Now().Zone()
	if off != wantOff || abbrev != clean(wantAbbrev, maxAbbrev) {
		t.Errorf("TimeZone() = %q %d %q, want offset %d abbrev %q", name, off, abbrev, wantOff, wantAbbrev)
	}
	if name != "" && !validTZName(name) {
		t.Errorf("TimeZone name %q invalid", name)
	}
	for _, a := range LANIPv4s() {
		if !a.Is4() || a.IsLoopback() || a.IsLinkLocalUnicast() {
			t.Errorf("LANIPv4s contains %v", a)
		}
	}
	if len(LANIPv4s()) > maxLANIPs {
		t.Error("LANIPv4s over cap")
	}
	host := HostAddrs()
	if len(host) > 0 && !containsAddr(host, netip.MustParseAddr("127.0.0.1")) && !containsAddr(host, netip.IPv6Loopback()) {
		t.Errorf("HostAddrs lacks loopback: %v", host)
	}
	for _, r := range Resolvers() {
		if !r.IsValid() || r.Port() == 0 {
			t.Errorf("resolver %v", r)
		}
	}
	_ = Hostname()
}

func TestSetMobileInfo(t *testing.T) {
	defer SetMobileInfo("", "", "", nil)
	SetMobileInfo(" 15\u202e ", "Pixel 9\n", "Europe/Berlin", []string{"192.168.1.1", "2001:db8::53", "[2001:db8::54]:5353", "bogus", "192.168.1.1", "10.0.0.1:0"})
	if v := OSVersion(); v != "15" {
		t.Errorf("OSVersion = %q", v)
	}
	if h := Hostname(); h != "Pixel 9" {
		t.Errorf("Hostname = %q", h)
	}
	name, off, abbrev := TimeZone()
	if name != "Europe/Berlin" {
		t.Errorf("tz name = %q", name)
	}
	if loc, err := time.LoadLocation("Europe/Berlin"); err == nil {
		wa, wo := time.Now().In(loc).Zone()
		if off != wo || abbrev != wa {
			t.Errorf("tz offset/abbrev = %d %q, want %d %q", off, abbrev, wo, wa)
		}
	}
	got := Resolvers()
	want := []string{"192.168.1.1:53", "[2001:db8::53]:53", "[2001:db8::54]:5353"}
	if len(got) != len(want) {
		t.Fatalf("Resolvers = %v", got)
	}
	for i := range want {
		if got[i].String() != want[i] {
			t.Errorf("Resolvers[%d] = %v, want %s", i, got[i], want[i])
		}
	}
	// Returned slice is a copy.
	got[0] = netip.AddrPort{}
	if Resolvers()[0].String() != want[0] {
		t.Error("Resolvers exposes internal slice")
	}

	// Invalid tz is ignored; clearing restores system values.
	SetMobileInfo("", "", "../../etc/passwd", nil)
	if name, _, _ := TimeZone(); name == "../../etc/passwd" {
		t.Error("invalid tz accepted")
	}
	if OSVersion() == "15" || Hostname() == "Pixel 9" {
		t.Error("override not cleared")
	}
}

